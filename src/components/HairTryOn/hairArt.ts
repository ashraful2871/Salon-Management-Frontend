const GROUP_FALLBACK: Record<string, string> = {
  short: "crew-cut",
  medium: "bob",
  long: "long-layers",
  curly: "natural-curls",
  fade: "low-fade",
};

export const artFor = (id: string, group?: string): HairArt =>
  ART[id] ?? ART[GROUP_FALLBACK[group ?? ""] ?? "crew-cut"];

/** Fades are clipped short at the sides; they get a shaded skin band. */
export const isFade = (id: string, group?: string) =>
  group === "fade" || id.includes("fade");
